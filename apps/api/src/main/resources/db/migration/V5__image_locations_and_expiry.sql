-- No backfill deadline: existing tasks, images, receipts and pending deletes stay local and permanent.
ALTER TABLE tasks ADD COLUMN expires_at BIGINT;
ALTER TABLE tasks ADD COLUMN write_bucket_id VARCHAR(36) REFERENCES r2_buckets(id);
CREATE INDEX tasks_expiry ON tasks(expires_at);
CREATE INDEX tasks_writing_bucket ON tasks(write_bucket_id);
ALTER TABLE images ADD COLUMN bucket_id VARCHAR(36) REFERENCES r2_buckets(id);
CREATE INDEX images_bucket ON images(bucket_id);

-- A timed-out PUT can have reached R2 even if its fallback was saved locally at the same URL.
-- Track both objects separately; neither a cloud outage nor a restart may lose a delete intent.
CREATE TABLE image_file_queue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url VARCHAR(200) NOT NULL,
    bucket_id VARCHAR(36) REFERENCES r2_buckets(id),
    task_id VARCHAR(36),
    owner_id VARCHAR(64),
    channel_id VARCHAR(36),
    staged BOOLEAN NOT NULL DEFAULT FALSE,
    not_before BIGINT NOT NULL DEFAULT 0,
    verify_after BIGINT
);
INSERT INTO image_file_queue(url) SELECT url FROM file_deletions;
DROP TABLE file_deletions;
ALTER TABLE image_file_queue RENAME TO file_deletions;
CREATE INDEX file_deletions_ready ON file_deletions(staged,id);
CREATE INDEX file_deletions_task ON file_deletions(task_id,staged);
CREATE INDEX file_deletions_bucket ON file_deletions(bucket_id);
